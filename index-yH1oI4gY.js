interface QuestionSeed {
  id: string;
  subject: SubjectId;
  difficulty: "Warm-up" | "Core" | "Stretch";
  question: string;
  questionZh: string;
  anchors: string[];
  insightEn: string;
  insightZh: string;
  answer: string;
  followUp: string;
  followUpZh: string;
  diagram?: DiagramKind;
  sketchPrompt?: string;
  sketchPromptZh?: string;
}

function buildQuestion(seed: QuestionSeed): InterviewQuestion {
  const firstAnchor = seed.anchors[0];
  const secondAnchor = seed.anchors[1] ?? seed.anchors[0];
  return {
    id: seed.id,
    subject: seed.subject,
    sourceMode: "mock",
    origin: "Perfect Oxbridge original",
    sourceTitle: "Perfect Oxbridge Interview extended bank",
    difficulty: seed.difficulty,
    question: seed.question,
    questionZh: seed.questionZh,
    zhGuide: seed.insightZh,
    guideEn: seed.insightEn,
    anchors: seed.anchors,
    hints: [
      "先从 " + firstAnchor + " 出发，定义关键变量、对象和需要保持不变的条件。",
      seed.insightZh + " 尝试画图、列一个简单例子或写出最小可用的关系式。",
      "用 " + secondAnchor + " 检查边界情况或反例，再把结论与原问题逐句对应。",
    ],
    hintsEn: [
      "Begin with " + firstAnchor + ": define the key quantities, objects and conditions that remain fixed.",
      seed.insightEn + " Draw a diagram, test a small case, or write the simplest useful relationship.",
      "Use " + secondAnchor + " to test a boundary case or counterexample, then connect the conclusion back to the exact wording.",
    ],
    modelAnswer: seed.answer,
    rubricKeywords: seed.anchors.map((anchor) => anchor.toLowerCase()),
    followUp: seed.followUp,
    followUpZh: seed.followUpZh,
    diagram: seed.diagram,
    sketchPrompt: seed.sketchPrompt,
    sketchPromptZh: seed.sketchPromptZh,
  };
}

